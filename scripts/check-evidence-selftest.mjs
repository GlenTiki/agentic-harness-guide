import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const source = 'examples/wrong-behaviour/results.json';
const rows = JSON.parse(fs.readFileSync(source, 'utf8'));
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'check-evidence-'));
const edited = path.join(dir, 'results.json');
rows[0].pass += 1;
fs.writeFileSync(edited, JSON.stringify(rows));
const run = (results) => spawnSync('node', ['scripts/make-evidence.mjs', '--check', '--results', results], { encoding: 'utf8' }).status;
const fresh = run(source);
const stale = run(edited);
const page = path.join(dir, 'evidence.mdx');
fs.writeFileSync(page, fs.readFileSync('src/content/docs/evidence/index.mdx', 'utf8'));
assert.equal(spawnSync('node', ['scripts/make-evidence.mjs', '--page', page], { encoding: 'utf8' }).status, 0);
const generated = fs.readFileSync(page, 'utf8');
assert.match(generated, /Legacy labels and corrected interpretation/);
assert.match(generated, /7,414 is the correct sum of all 40 supplied amounts/);
assert.match(generated, /unknown service-error contribution/);
assert.match(generated, /metadata-match credit without comparing/);
assert.match(generated, /email-shaped strings were redacted/);
const prospective = path.join(dir, 'prospective.json');
const newRows = JSON.parse(fs.readFileSync(source, 'utf8')).map((row) => ({ ...row, grader_version: 'doi sha256 new' }));
fs.writeFileSync(prospective, JSON.stringify(newRows));
const refused = spawnSync('node', ['scripts/make-evidence.mjs', '--results', prospective, '--page', page], { encoding: 'utf8' });
assert.equal(refused.status, 1, 'new grader outcomes must not acquire historical claims');
assert.match(refused.stderr, /separately reviewed report/);
assert.equal(fs.readFileSync(page, 'utf8'), generated, 'refusal must leave the page untouched');
fs.writeFileSync(page, generated.replace('## What was tested', '## Edited generated heading'));
const outdated = spawnSync('node', ['scripts/make-evidence.mjs', '--check', '--page', page], { encoding: 'utf8' });
assert.equal(outdated.status, 1);
assert.match(outdated.stdout, /OUT OF DATE/);
fs.rmSync(dir, { recursive: true });
console.log(`self-test: edited results exit ${stale} (must be 1), real results exit ${fresh} (must be 0)`);
process.exit(stale === 1 && fresh === 0 ? 0 : 1);
